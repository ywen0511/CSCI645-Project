"""CPU-only V5 Study B case design: dynamic in-grasp slip (standard library only).

A V5 slip case = a V4 case (shared physical base draw, in-grasp start offset, sensor corruption; generated by
``v4_protocol.make_cases``) + a slip: ``slip_xyz_m`` (target displacement inside the giver grasp, env-local,
x = bar axis toward the receiver), ``slip_onset_s`` (scored time) and ``slip_duration_s``. The onset is keyed to
the base case (paired across conditions); the slip magnitude is keyed per condition. Every slip draw is clamped
so that the cumulative in-grasp offset (start x + slip x) stays inside the feasible range accepted by the
development probe (docs/v5/SLIP_FEASIBILITY.md).
"""

from __future__ import annotations

import random

from . import v4_protocol as v4

SPLIT_SEEDS = {"development": 6458101, "validation": 6458201, "final": 6458301}
ANALYSIS_SEED = 6458401
EVAL_SEED = 6458501
REPEAT_SEED = 6458601
TRAINING_SEEDS = (111, 222, 333, 444, 555)
SPLIT_COUNTS = {"development": 24, "validation": 40, "final": 200}
PREFIX = "v5slip"

SLIP_DURATION_S = 0.25
ONSET_RANGE_S = (0.7, 1.4)
# Feasible cumulative in-grasp x range [m], from the development probe (results/v5/slip/probe/summary.json,
# docs/v5/SLIP_FEASIBILITY.md): mechanism M6 realized valid slips at -2, +2, +5 and +10 mm in 12/12 episodes each;
# +15 mm (vertical sag) and -5 / -7 mm (toward the giver palm: tipping, palm contact) failed acceptance.
CUMULATIVE_X = (-0.002, 0.010)
# Selected slip mechanism (probe round 2, "M6"): the giver keeps its full closed squeeze (grip_force_n equals the
# closed command, so the finger target is unchanged) and a PID-regulated bar-axis force (<= 90 N) at the bar's
# centre of mass overcomes friction; the regulator holds the target for 0.1 s afterwards.
SLIP_MECHANISM = {"finger_stiffness": 2000.0, "kp": 6000.0, "kd": 60.0, "ki": 60000.0, "regrip_s": 0.1,
                  "tolerance_m": 0.0015, "grip_force_n": 35.0, "force_max_n": 90.0}

S0: dict = {}
MIXED_ID = v4.CONDITIONS["mixed_id"]
MIXED_OOD = v4.CONDITIONS["mixed_ood"]
CONDITIONS = {
    "clean": {"physical": False, "grasp": {"mode": "zero"}, "sensor": S0, "slip": None},
    "static_mixed_id": {"grasp": MIXED_ID["grasp"], "sensor": MIXED_ID["sensor"], "slip": None},
    "slip_pos_5": {"grasp": {"mode": "zero"}, "sensor": S0, "slip": {"fixed": 0.005}},
    "slip_pos_10": {"grasp": {"mode": "zero"}, "sensor": S0, "slip": {"fixed": 0.010}},
    # V5_EXECUTION.md lists slip_neg_5; -5 mm is outside the feasible range, so the bound is adjusted to -2 mm
    "slip_neg_2": {"grasp": {"mode": "zero"}, "sensor": S0, "slip": {"fixed": -0.002}},
    "slip_after_offset": {"grasp": {"x": {"fixed": 0.010}}, "sensor": S0, "slip": {"fixed": -0.010}},
    "slip_mixed_id": {"grasp": MIXED_ID["grasp"], "sensor": MIXED_ID["sensor"], "slip": {"uniform": [-0.005, 0.010]}},
    "slip_mixed_ood": {"grasp": MIXED_OOD["grasp"], "sensor": MIXED_OOD["sensor"], "slip": {"uniform": [-0.007, 0.015]}},
}
ORDER = list(CONDITIONS)
PRIMARY = "slip_mixed_id"
VALIDATION = ("clean", "static_mixed_id", "slip_pos_10", "slip_mixed_id")
TRAIN_SLIP = {"probability": 0.5, "x_uniform": [-0.005, 0.010], "onset_uniform": list(ONSET_RANGE_S),
              "duration_s": SLIP_DURATION_S, "cumulative_x": list(CUMULATIVE_X)}


def clamp_cumulative(grasp_x: float, slip_x: float, lo: float, hi: float) -> float:
    return min(max(grasp_x + slip_x, lo), hi) - grasp_x


def slip_fields(rule: dict | None, grasp_x: float, srng: random.Random, onset: float,
                cumulative=CUMULATIVE_X, duration=SLIP_DURATION_S) -> dict:
    """rule None = no slip; {"fixed": x} | {"uniform": [lo, hi]}; the result is clamped cumulatively."""
    if rule is None:
        return {"slip_xyz_m": [0.0, 0.0, 0.0], "slip_onset_s": 0.0, "slip_duration_s": 0.0, "slip_clamped": False}
    raw = float(rule["fixed"]) if "fixed" in rule else srng.uniform(*rule["uniform"])
    x = clamp_cumulative(grasp_x, raw, *cumulative)
    return {"slip_xyz_m": [round(x, 9), 0.0, 0.0], "slip_onset_s": round(onset, 9), "slip_duration_s": duration,
            "slip_clamped": abs(x - raw) > 1e-12, "slip_requested_x_m": round(raw, 9)}


def make_cases(split: str, conditions: dict | None = None, order: list[str] | None = None, *,
               count: int | None = None, seed: int | None = None, prefix: str = PREFIX,
               cumulative=CUMULATIVE_X) -> list[dict]:
    conditions = CONDITIONS if conditions is None else conditions
    order = ORDER if order is None else order
    seed = SPLIT_SEEDS[split] if seed is None else seed
    count = SPLIT_COUNTS[split] if count is None else count
    base = v4.make_cases(split, conditions, order, count=count, seed=seed, prefix=prefix)
    rows = []
    for r in base:
        i = int(r["base_case_id"].rsplit("-", 1)[1])
        cond = r["condition"]
        orng = random.Random(v4.case_seed(seed, i, "slip_onset"))
        onset = orng.uniform(*ONSET_RANGE_S)
        srng = random.Random(v4.case_seed(seed, i, "slip", cond))
        r.update(slip_fields(conditions[cond].get("slip"), r["grasp_offset_xyz_m"][0], srng, onset, cumulative))
        r["suite_version"] = 5
        rows.append(r)
    return rows


def probe_cases(targets_mm=(-7, -5, -2, 2, 5, 10, 15), onsets=(0.7, 1.05, 1.4), count: int = 4) -> list[dict]:
    """Development-only feasibility probe (development seed, key "probe"): fixed slip targets (cumulative
    offset = target, start offset 0, z = 0) x fixed onsets, plus a no-slip control; ``count`` base cases each,
    base case 0 without joint displacement or release offset."""
    conds = {"noslip": {"grasp": {"mode": "zero"}, "sensor": S0, "slip": None}}
    for t in targets_mm:
        for on in onsets:
            conds[f"x{t:+d}_on{int(round(on * 100)):03d}"] = {"grasp": {"mode": "zero"}, "sensor": S0,
                                                             "slip": {"fixed": t / 1000.0}, "onset": on}
    seed = v4.case_seed(SPLIT_SEEDS["development"], "probe")
    base = v4.make_cases("development", conds, list(conds), count=count, seed=seed, prefix=f"{PREFIX}probe")
    rows = []
    for r in base:
        spec = conds[r["condition"]]
        if r["base_case_id"].endswith("-0000"):
            r["requested_offset_xyz_m"], r["release_offset_s"] = [0.0, 0.0, 0.0], 0.0
        r.update(slip_fields(spec["slip"], 0.0, random.Random(0), spec.get("onset", 0.0), cumulative=(-1.0, 1.0)))
        r["suite_version"] = 5
        rows.append(r)
    return rows
